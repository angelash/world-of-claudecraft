// Text key types (release_engineering.md 8.2): writes src/core/text_keys.generated.ts, the
// union of every key in the source string tables (locales/zh-Hans/ui.json and sys_*.json;
// the generated content table is left out, its keys are built by tools). tr() in
// src/core/text.ts and t() in src/shared_ui/i18n.ts take a key argument checked against it,
// so a misspelt literal key fails the type check. The file lives in src/core because the
// kernel may not import src/shared_ui (tests/i18n_kernel_guard.test.ts); it holds key names
// only, no text.
//
//   node tools/i18n/gen_keys.ts           write the file
//   node tools/i18n/gen_keys.ts --check   fail when the file is stale
//
// Plain Node (no Vite): reads the JSON tables directly.

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SOURCE_DIR = join(ROOT, 'locales', 'zh-Hans');
export const KEYS_PATH = 'src/core/text_keys.generated.ts';

/** The source table files the key union covers (generated tables excluded). */
export function sourceTableFiles(dir: string = SOURCE_DIR): string[] {
  return readdirSync(dir)
    .filter((f) => f.endsWith('.json') && !f.endsWith('.generated.json'))
    .sort();
}

/** The generated TypeScript text for a set of keys. */
export function formatKeys(keys: readonly string[]): string {
  const sorted = [...new Set(keys)].sort();
  const lines = [
    '// Generated by tools/i18n/gen_keys.ts from locales/zh-Hans/ (ui.json, sys_*.json).',
    '// Do not edit: run `node tools/i18n/gen_keys.ts` after changing a string table.',
    '',
    '/** Every key of the source string tables (the ui., sys. and tut. scopes). */',
    'export type TextKey =',
    ...sorted.map((k, i) => `  | '${k}'${i === sorted.length - 1 ? ';' : ''}`),
    '',
    `/** Number of keys in TextKey (${sorted.length}). */`,
    `export const TEXT_KEY_COUNT = ${sorted.length};`,
    '',
  ];
  return lines.join('\n');
}

function main(): number {
  const keys: string[] = [];
  for (const f of sourceTableFiles()) {
    const table = JSON.parse(readFileSync(join(SOURCE_DIR, f), 'utf8')) as Record<string, unknown>;
    keys.push(...Object.keys(table));
  }
  const text = formatKeys(keys);
  const out = join(ROOT, KEYS_PATH);
  if (process.argv.includes('--check')) {
    const current = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== text) {
      console.error(`text keys: ${KEYS_PATH} is stale; run node tools/i18n/gen_keys.ts`);
      return 1;
    }
    console.log(`text keys: ${KEYS_PATH} is current (${new Set(keys).size} keys)`);
    return 0;
  }
  writeFileSync(out, text);
  console.log(`text keys: wrote ${KEYS_PATH} (${new Set(keys).size} keys)`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main();
}
