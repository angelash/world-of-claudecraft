export function buildUpstreamNpcProfilePack(base: AiAgentProfile): readonly AiAgentProfile[] {
  return UPSTREAM_NPC_ROLES.map((role) => ({
    ...base,
    id: `npc.upstream.${role.id}.living_world`,
    appliesTo: role.templateIds.map((templateId) => ({ kind: 'npc', templateId })),
    persona: role.persona,
    allowedIntentTypes: [...base.allowedIntentTypes],
    allowedLineIds: [...base.allowedLineIds],
    canonSensitive: true,
    knowledgeScope: [...base.knowledgeScope, role.knowledge],
    tabooTopics: [...base.tabooTopics],
    socialMemory: { ...base.socialMemory },
    itemInterest: {
      attractedToTags: [...(base.itemInterest?.attractedToTags ?? []), role.itemTag],
      avoidsTags: [...(base.itemInterest?.avoidsTags ?? [])],
    },
  }));
}
